#!/usr/bin/env node
// What the signer's WASM module can reach, checked on a built package (`ui/src/wasm-pkg`, or the
// package CI builds from source). One rule, run in two places: the vitest `ui/src/wasm-pkg-check.test.ts`
// on the committed package, and the CI `wasm` job on the package it has just built, so a dependency
// change that gives the module a new capability fails before anyone regenerates the committed copy.
//
// The share is used inside this module. What it can call is the set of functions the JS glue hands it
// at instantiation (`import0` in `konclave_wasm.js`): the `.wasm` only names them, the glue decides what
// each one DOES. So the check is on (name, body) pairs, reviewed in `scripts/wasm-imports.allowlist.json`:
//   1. every import of the `.wasm` comes from the glue module `./konclave_wasm_bg.js`;
//   2. the glue's import object has exactly the `.wasm`'s import names, no more, no fewer;
//   3. every (name, body) pair is in the reviewed list, byte for byte after whitespace is collapsed;
//   4. the glue imports and re-exports nothing (no `import`, no `from '...'`), and the package holds no
//      other JS file and no `snippets/` (inline or module JS);
//   5. the memory is defined by the module, not imported, and not shared;
//   6. the wasm-bindgen that built the package (the `.wasm` producers section) is the one Cargo.lock pins;
//   7. the glue's runtime, every top-level function and binding that is not an exported wrapper
//      (the helpers the import bodies call, the loader with its fetch of the `.wasm`, the caches),
//      is the reviewed text too;
//   8. as an alarm over the exported wrappers, which rules 3 and 7 do not pin: comments stripped,
//      they name no network, storage, worker, messaging, reflective or global-object API, no fetch,
//      and assign to no runtime name.
// What rules 3 and 7 pin is TEXT. Against a dependency that changes what wasm-bindgen generates, they
// hold: a new import or a new runtime body is a diff to review. Against someone who hand-edits the
// committed glue they are not a guarantee (an exported wrapper can rebind a helper, or reach a
// global by a computed name that no list of words sees); that guarantee is the byte-for-byte
// comparison of the committed package with a build from source (#1065).
// This says the module cannot open a channel of its own. It does not say a hostile dependency cannot
// leak through what the module legitimately returns, which the JS around it then sends: the module
// chooses the FROST nonces, so a dependency that knew them could recover the share from one signature
// share the relay carries, and the same holds for sealing ephemerals. Which crates enter the module
// (Cargo.lock) is where that residual is decided, not here.
//
// Usage: node scripts/check-wasm-pkg.mjs <pkg-dir> [--write-allowlist]
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const HERE = dirname(fileURLToPath(import.meta.url))
const ROOT = resolve(HERE, '..')
export const ALLOWLIST = join(HERE, 'wasm-imports.allowlist.json')
const NAME = 'konclave_wasm'
const GLUE_MODULE = `./${NAME}_bg.js`

/** Collapse whitespace so formatting is not a difference; the code itself must match exactly. */
const norm = (s) => s.replace(/\s+/g, ' ').trim()

/** The entries of the glue's `import0` object: name -> normalised body. Throws if it is not found. */
export function glueImports(glue) {
  const fn = glue.indexOf('\nfunction __wbg_get_imports() {')
  if (fn < 0 || glue.indexOf('\nfunction __wbg_get_imports() {', fn + 1) >= 0) {
    throw new Error('glue: not exactly one `function __wbg_get_imports()`')
  }
  const fnEnd = glue.indexOf('\n}\n', fn)
  const body = glue.slice(fn, fnEnd < 0 ? glue.length : fnEnd)
  const first = body.indexOf('const import0 = {')
  if (first < 0) throw new Error('glue: no `const import0 = {` (generated by another wasm-bindgen?)')
  if (body.indexOf('const import0 = {', first + 1) >= 0) throw new Error('glue: more than one `const import0 = {`')
  const start = fn + first
  const end = glue.indexOf('\n    };', start)
  if (end < 0) throw new Error('glue: the import object does not end where expected')
  const block = glue.slice(start, end)
  const entries = new Map()
  const re = /^ {8}([A-Za-z_$][\w$]*): /gm
  const marks = [...block.matchAll(re)].map((m) => ({ name: m[1], at: m.index, body: m.index + m[0].length }))
  marks.forEach((m, i) => {
    // `__proto__: null` makes the object prototype-free; it is not an import.
    if (m.name === '__proto__') return
    const stop = i + 1 < marks.length ? marks[i + 1].at : block.length
    entries.set(m.name, norm(block.slice(m.body, stop)).replace(/,$/, ''))
  })
  return entries
}

function readLeb(bytes, at) {
  let result = 0, shift = 0, b
  do {
    b = bytes[at++]
    result |= (b & 0x7f) << shift
    shift += 7
  } while (b & 0x80)
  return [result >>> 0, at]
}

/** The memory section's limits flags, one per memory the module defines. */
export function memoryFlags(bytes) {
  const out = []
  let at = 8
  while (at < bytes.length) {
    const id = bytes[at++]
    let size
    ;[size, at] = readLeb(bytes, at)
    if (id === 5) {
      let count, p = at
      ;[count, p] = readLeb(bytes, p)
      for (let i = 0; i < count; i++) {
        const flags = bytes[p++]
        out.push(flags)
        ;[, p] = readLeb(bytes, p)
        if (flags & 0x01) [, p] = readLeb(bytes, p)
      }
    }
    at += size
  }
  return out
}

/** The `processed-by` tools of a producers custom section: name -> version string. */
export function producers(section) {
  const bytes = new Uint8Array(section)
  const str = (p) => {
    let len
    ;[len, p] = readLeb(bytes, p)
    return [new TextDecoder().decode(bytes.subarray(p, p + len)), p + len]
  }
  const tools = new Map()
  let p = 0, fields, field, n, name, ver
  ;[fields, p] = readLeb(bytes, p)
  for (let i = 0; i < fields; i++) {
    ;[field, p] = str(p)
    ;[n, p] = readLeb(bytes, p)
    for (let j = 0; j < n; j++) {
      ;[name, p] = str(p)
      ;[ver, p] = str(p)
      if (field === 'processed-by') tools.set(name, ver)
    }
  }
  return tools
}

/** The version of `crate` that `Cargo.lock` resolves, or null. */
export function lockedVersion(lock, crate) {
  const m = lock.match(new RegExp(`\\[\\[package\\]\\]\\nname = "${crate}"\\nversion = "([^"]+)"`))
  return m ? m[1] : null
}

/** The glue's top-level items, in order: a key and the normalised text. An item starts on a line with
 *  no indentation that is not a closing brace or a comment, and runs to the next such line. */
export function topLevel(glue) {
  const items = []
  let cur = null
  const seen = new Map()
  for (const line of glue.split('\n')) {
    const starts = /^[^\s}/*]/.test(line) && !line.startsWith('//')
    if (starts) {
      if (cur) items.push(cur)
      const m = line.match(/^(?:export\s+)?(?:default\s+)?(?:async\s+)?(?:function\*?|class|const|let|var)\s+([A-Za-z_$][\w$]*)/)
      let key = m ? m[1] : `stmt:${norm(line).slice(0, 40)}`
      const n = (seen.get(key) ?? 0) + 1
      seen.set(key, n)
      if (n > 1) key = `${key}#${n}`
      cur = { key, exported: /^export\b/.test(line), text: line }
    } else if (cur) {
      cur.text += '\n' + line
    }
  }
  if (cur) items.push(cur)
  // Comments are not code: a doc comment that wasm-bindgen copies from the Rust changes nothing.
  return items.map((i) => ({ ...i, text: norm(stripComments(i.text)) }))
}

/** The runtime rule 7 pins: every top-level item that is not an exported wrapper and not the import
 *  object (pinned entry by entry by rule 3). */
export function glueRuntime(glue) {
  const out = {}
  for (const i of topLevel(glue)) {
    if (i.exported) continue
    // The import object's entries are rule 3's; the rest of the function that builds it is pinned
    // here, so an entry reassigned before the object is returned is seen.
    out[i.key] = i.key === '__wbg_get_imports' ? withoutImportEntries(i.text) : i.text
  }
  return out
}

/** `__wbg_get_imports` with the entries of `import0` cut out (normalised text in, text out). */
function withoutImportEntries(text) {
  const start = text.indexOf('const import0 = {')
  const end = text.indexOf('};', start)
  return start < 0 || end < 0 ? text : text.slice(0, start) + 'const import0 = {…' + text.slice(end)
}

/** APIs the glue may not name: network, storage, workers, messaging and reflection. Whole words. */
export const DENIED = [
  'XMLHttpRequest', 'WebSocket', 'WebTransport', 'sendBeacon', 'importScripts', 'EventSource', 'indexedDB',
  'localStorage', 'sessionStorage', 'cookie', 'Worker', 'SharedWorker', 'postMessage', 'BroadcastChannel',
  'RTCPeerConnection', 'Image', 'eval', 'Function', 'Reflect', 'Proxy', 'navigator', 'document', 'location',
  'setTimeout', 'setInterval', 'parent', 'top', 'frames', 'globalThis', 'self', 'window', 'global',
  'crypto', 'atob', 'btoa', 'fetch',
]
/** Shapes a whole-word list cannot say: a constructor reached through a value, a window opened. */
export const DENIED_SHAPES = [/\.\s*constructor\b/, /\bwindow\s*\.\s*open\b/, /\.\s*opener\b/]

/** `src` without comments; strings are kept (a URL in a string is still a capability). */
function stripComments(src) {
  return src.replace(/\/\*[\s\S]*?\*\//g, ' ').replace(/(^|[^:'"`\\])\/\/[^\n]*/g, '$1')
}


/** Everything wrong with the package in `dir`; empty when it holds. */
export function checkWasmPkg(dir, opts = {}) {
  const problems = []
  const wasm = readFileSync(join(dir, `${NAME}_bg.wasm`))
  const glue = readFileSync(join(dir, `${NAME}.js`), 'utf8')
  const reviewed = opts.reviewed ?? JSON.parse(readFileSync(ALLOWLIST, 'utf8'))
  const allow = opts.allowlist ?? reviewed.imports
  const runtimeAllow = opts.runtime ?? reviewed.runtime ?? {}
  const lock = opts.cargoLock ?? readFileSync(join(ROOT, 'Cargo.lock'), 'utf8')

  const mod = new WebAssembly.Module(wasm)
  const imports = WebAssembly.Module.imports(mod)
  for (const i of imports) {
    if (i.module !== GLUE_MODULE) problems.push(`import ${i.module}:${i.name} does not come from ${GLUE_MODULE}`)
    if (i.kind !== 'function') problems.push(`import ${i.name} is a ${i.kind}, not a function`)
  }

  let given
  try {
    given = glueImports(glue)
  } catch (e) {
    problems.push(String(e.message))
    given = new Map()
  }
  const wanted = new Set(imports.map((i) => i.name))
  for (const n of wanted) if (!given.has(n)) problems.push(`the .wasm imports ${n}, which the glue does not provide`)
  for (const n of given.keys()) if (!wanted.has(n)) problems.push(`the glue provides ${n}, which the .wasm does not import`)
  for (const [n, body] of given) {
    if (!(n in allow)) problems.push(`import ${n} is not in the reviewed list: ${body}`)
    else if (allow[n] !== body) problems.push(`import ${n} does something other than the reviewed body: ${body}`)
  }

  const code = stripComments(glue)
  if (/^\s*import\s/m.test(code) || /\bimport\s*["'`(]/.test(code.replace(/import\.meta/g, ''))) {
    problems.push('the glue has an import statement (inline or module JS)')
  }
  if (/\bfrom\s*['"`]/.test(code)) problems.push('the glue re-exports from another module')
  for (const f of readdirSync(dir)) {
    if (/\.(m?js|cjs)$/.test(f) && f !== `${NAME}.js`) problems.push(`the package holds another JS file: ${f}`)
  }
  const runtime = glueRuntime(glue)
  for (const [k, text] of Object.entries(runtime)) {
    if (!(k in runtimeAllow)) problems.push(`the glue runtime has ${k}, which is not in the reviewed list: ${text.slice(0, 160)}`)
    else if (runtimeAllow[k] !== text) problems.push(`the glue runtime ${k} differs from the reviewed text: ${text.slice(0, 160)}`)
  }
  for (const k of Object.keys(runtimeAllow)) if (!(k in runtime)) problems.push(`the reviewed glue runtime ${k} is missing`)

  // Rule 8: the exported wrappers, the one part of the glue rules 3 and 7 do not pin.
  const exported = topLevel(glue).filter((i) => i.exported).map((i) => i.text).join('\n')
  for (const d of DENIED) if (new RegExp(`\\b${d}\\b`).test(exported)) problems.push(`an exported wrapper names ${d}`)
  for (const r of DENIED_SHAPES) if (r.test(exported)) problems.push(`an exported wrapper matches ${r}`)
  for (const name of Object.keys(runtime)) {
    if (/^[A-Za-z_$][\w$]*$/.test(name) && new RegExp(`(^|[^\\w$.])${name.replace(/\$/g, '\\$')}\\s*=(?!=)`).test(exported)) {
      problems.push(`an exported wrapper assigns to the runtime's ${name}`)
    }
  }
  if (existsSync(join(dir, 'snippets'))) problems.push('the package has a snippets/ directory')

  const flags = memoryFlags(wasm)
  if (flags.length !== 1) problems.push(`the module defines ${flags.length} memories, not one`)
  if (flags.some((f) => f & 0x02)) problems.push('the module memory is shared')
  if (!WebAssembly.Module.exports(mod).some((e) => e.kind === 'memory')) problems.push('the module exports no memory')

  const sections = WebAssembly.Module.customSections(mod, 'producers')
  if (sections.length > 1) problems.push(`the .wasm has ${sections.length} producers sections, not one`)
  const built = sections.length === 1 ? producers(sections[0]).get('wasm-bindgen') : undefined
  const pinned = lockedVersion(lock, 'wasm-bindgen')
  if (!built) problems.push('the .wasm names no wasm-bindgen in its producers section')
  else if (!pinned) problems.push('Cargo.lock resolves no wasm-bindgen')
  else if (built.split(' ')[0] !== pinned) problems.push(`built by wasm-bindgen ${built}, Cargo.lock pins ${pinned}`)
  return problems
}

/** The reviewed list as the package in `dir` would have it: for `--write-allowlist`, then review. */
export function allowlistFor(dir) {
  const glue = readFileSync(join(dir, `${NAME}.js`), 'utf8')
  return { imports: Object.fromEntries(glueImports(glue)), runtime: glueRuntime(glue) }
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const dir = process.argv[2]
  if (!dir) {
    console.error('usage: node scripts/check-wasm-pkg.mjs <pkg-dir> [--write-allowlist]')
    process.exit(2)
  }
  if (process.argv.includes('--write-allowlist')) {
    const current = JSON.parse(readFileSync(ALLOWLIST, 'utf8'))
    writeFileSync(ALLOWLIST, JSON.stringify({ ...current, ...allowlistFor(dir) }, null, 2) + '\n')
    console.log(`wrote ${ALLOWLIST}: review every changed body before committing`)
    process.exit(0)
  }
  const problems = checkWasmPkg(dir)
  for (const p of problems) console.error(`wasm-pkg: ${p}`)
  if (problems.length) process.exit(1)
  console.log(`wasm-pkg: ${dir} holds (imports and glue runtime reviewed, memory not shared, wasm-bindgen as pinned)`)
}
